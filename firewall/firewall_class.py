"""Basic SQL firewall for the proof-of-concept application."""

import re


class QueryBlockedError(PermissionError):
    """Raised when the SQL firewall rejects a query."""


class BasicSQLFirewall:
    """Allow read queries and reject SQL keywords that can modify state."""

    # Ignore keywords that only occur inside comments, string values, or quoted
    # identifiers. For example, SELECT 'delete' should remain a valid read query.
    _IGNORED_SQL = re.compile(
        r"--[^\r\n]*|/\*.*?\*/|'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"",
        flags=re.DOTALL,
    )
    # These keywords represent data modification, schema changes, permission
    # changes, or database administration and are blocked by this PoC firewall.
    _BLOCKED_KEYWORDS = re.compile(
        r"\b("
        r"INSERT|UPDATE|DELETE|MERGE|CREATE|ALTER|DROP|TRUNCATE|"
        r"GRANT|REVOKE|COMMENT|COPY|CALL|DO|EXECUTE|PREPARE|"
        r"VACUUM|ANALYZE|CLUSTER|REINDEX|REFRESH|LOCK|SET|RESET|"
        r"DISCARD|INTO"
        r")\b",
        flags=re.IGNORECASE,
    )
    # After the deny-list check, only statements beginning with an explicitly
    # allowed read-oriented command can proceed.
    _ALLOWED_START = re.compile(
        r"^\s*(SELECT|WITH|SHOW|EXPLAIN)\b",
        flags=re.IGNORECASE,
    )

    def validate_query(self, query: str) -> None:
        """Check whether SQL is acceptable for protected execution.

        Args:
            query: Complete SQL generated by the model.

        Raises:
            QueryBlockedError: If the query is empty, contains a blocked
                keyword, or does not begin with an allowed read command.
        """
        print("[Firewall] Activated: inspecting the model-generated SQL.")

        # Reject missing input before applying regular-expression checks.
        if not query or not query.strip():
            print("[Firewall] BLOCKED: the query is empty.")
            raise QueryBlockedError("The firewall blocked an empty query.")

        # Remove text that must not be interpreted as executable SQL keywords.
        inspected_query = self._IGNORED_SQL.sub(" ", query)
        blocked_keyword = self._BLOCKED_KEYWORDS.search(inspected_query)

        # Report the first modifying or administrative keyword that was found.
        if blocked_keyword:
            print(
                "[Firewall] BLOCKED: detected SQL keyword "
                f"{blocked_keyword.group(1).upper()}."
            )
            raise QueryBlockedError(
                "The firewall blocked the SQL keyword "
                f"{blocked_keyword.group(1).upper()}."
            )

        # The allow-list rejects unknown statement types even when none of the
        # deny-list keywords were detected.
        if not self._ALLOWED_START.match(inspected_query):
            print("[Firewall] BLOCKED: the statement type is not allowed.")
            raise QueryBlockedError(
                "The firewall only allows SELECT, WITH, SHOW, or EXPLAIN queries."
            )

        print("[Firewall] ALLOWED: the query passed inspection.")
